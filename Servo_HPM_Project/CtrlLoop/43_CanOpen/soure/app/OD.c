/**
 * @brief 初始化对象字典，将0x1000、0x6000、0x3000整合在一起提供给协议层
 *
 * @param  param1 : void
 * @return uint8_t : 0 not error
 */
#include "SensorlessCanopen.h"
extern OD_entry_t g_sl_can_od[SL_CAN_OD_COUNT];
extern void SensorlessCanopen_InitOd(void);
uint8_t CO_init_OD(void)
{
    
    uint16_t OD_Size_H1xxx = sizeof(ODList_H1xxx) / sizeof(OD_entry_t);
    uint16_t OD_Size_H2xxx = 0;
    uint16_t OD_Size_H6xxx = sizeof(ODList_H6xxx) / sizeof(OD_entry_t);
    uint16_t OD_Size_All = 0;
    OD_entry_t *ODList_Index = ODList_Addr;

    //计算H2xxx参数组的总量
    for(uint16_t i = 0; i < (sizeof(_OD_Para_Sub)/sizeof(OD_Sub_t)) ;i++)
    {
        OD_Size_H2xxx += _OD_Para_Sub[i].size;
    }

    OD_Size_All = OD_Size_H1xxx + OD_Size_H2xxx + OD_Size_H6xxx + SL_CAN_OD_COUNT;

    if(OD_Size_All >= OD_ALL_NUM)
    {
        return 1;
    }

    //分配空间
    //ODList_Addr = (OD_entry_t*)malloc((OD_Size_All + 1)*sizeof(OD_entry_t));
    ODList_Addr = ODListArr;

    if(ODList_Addr == NULL)
    {
        return 1;
    }

    ODList_Index = ODList_Addr;

    //将三个区域的对象整合成一个对象列表
    //通讯配置
    memcpy(ODList_Index, ODList_H1xxx, sizeof(ODList_H1xxx));

    ODList_Index += OD_Size_H1xxx;
    SensorlessCanopen_InitOd();
    memcpy(ODList_Index, g_sl_can_od, sizeof(OD_entry_t)*SL_CAN_OD_COUNT);
    ODList_Index += SL_CAN_OD_COUNT;

    //P0-PF参数组
    for(uint16_t i = 0; i < (sizeof(_OD_Para_Sub)/sizeof(OD_Sub_t)) ;i++)
    {
        //数据类型转换 Myobj -> OD_entry_t
        for(uint16_t j = 0; j < _OD_Para_Sub[i].size ;j++)
        {
            ODList_Index->index           =  (_OD_Para_Sub[i].list + j)->index;
            ODList_Index->subEntriesCount =  (_OD_Para_Sub[i].list + j)->subEntriesCount;
            ODList_Index->odObjectType    =  (_OD_Para_Sub[i].list + j)->odObjectType;
            ODList_Index->odObject        = &(_OD_Para_Sub[i].list + j)->Myobj;
            ODList_Index->extension       =  (_OD_Para_Sub[i].list + j)->extension;

            ODList_Index += 1;
        }
    }

    //402协议
    memcpy(ODList_Index, ODList_H6xxx, sizeof(ODList_H6xxx));

    ODList_Index += OD_Size_H6xxx;

    //最后一个对象置0
    memset(ODList_Index , 0, sizeof(OD_entry_t));

    _OD.size = OD_Size_All;
    _OD.list = ODList_Addr;

    return 0;
}

/**
 * @brief  重写OD_writeOriginal()，增加电机参数的取值范围检查
 *         TODO: 密码权限判断？PE组 PF组 无OD 
 * @param OD_stream_t stream :  对象字典的相关属性
 * @param void* buf :  数据缓存区
 * @param OD_size_t count : 目标写入长度
 * @param OD_size_t countWritten : 实际写入长度
 * @return ODR_t : 0 not error
 */
ODR_t OD_writeOriginal_servoPara(OD_stream_t* stream, const void* buf, OD_size_t count, OD_size_t* countWritten)
{
    /* Legacy drive parameter writes must not change calibration during a test. */
    if(StateMachine.RegulFlg != 0U) return ODR_DATA_DEV_STATE;
    TYPE_WORD Rx_Func;
    TYPE_WORD W_Data;

    TYPE_Attribute *Attr;
    uint16_t *Addr;
    uint16_t index = stream->index;
    uint8_t checkCnt = 0;

    if ((stream == NULL) || (buf == NULL) || (countWritten == NULL)) 
    {
        return ODR_DEV_INCOMPAT;
    }

    //暂不考虑单字节 和 段操作
    if ((count < 2) || (count > 4)) 
    {
        return ODR_DEV_INCOMPAT;
    }
    
    checkCnt = count / 2;

    //取数据 2字节 or 4字节
    for(int i = 0; i < checkCnt; i++)
    {
        index = stream->index + i;
        
        //索引转换为参数地址，仅支持上位机的参数，0x1000和0x6000可直接通过SDO索引进行操作
        if((index & 0x3000) == 0x3000)
        {
            Rx_Func.Byte.High = (index & 0x0F00) >> 8; /*取寄存器的地址*/
            Rx_Func.Byte.Low  = (index & 0x00FF);
        }
        else
        {
            return ODR_DEV_INCOMPAT;
        }

        (void)memcpy(&W_Data, (const void*)buf + i*2, 2);
    
        //阈值判断
        Attr = FuncAttrStartAddr + GetFuncAddr(Rx_Func.all);

        if(Attr->Sign == USIGN)
        {
            if((W_Data.all > Attr->Max.U) || (W_Data.all < Attr->Min.U))
            {         
                return ODR_PAR_INCOMPAT;     //直接通过SDO报错传出去
            }
        }
        else
        {
            if(((int16_t)W_Data.all > Attr->Max.S) || ((int16_t)W_Data.all < Attr->Min.S))
            {
                return ODR_PAR_INCOMPAT;    //直接通过SDO报错传出去
            }
        }
    }

    //调用SDO写函数
    return OD_writeOriginal(stream, buf, count, countWritten);
}

