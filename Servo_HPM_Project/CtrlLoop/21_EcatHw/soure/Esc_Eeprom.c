#define IIC_SCL    (PORTC.PODR.BIT.B4)  //SCL
#define IIC_SDA    (PORTC.PODR.BIT.B5)  //SDA	 
#define READ_SDA   (PORTC.PIDR.BIT.B5)  //输入SDA 

void Delay_2us(void)
{
    uint16_t loop;
    
    for (loop = 0; loop < 100 ; loop++ )  
    {
        asm volatile("nop");  
    }
}

void Delay_4us(void)
{
    uint16_t loop;
    
    for (loop = 0; loop < 200 ; loop++ )  
    {
        asm volatile("nop");  
    }
}

void Delay(uint16_t u)
{
    while(u!=0)
    {
        Delay_4us();
        u--;
    }	
}

//产生IIC起始信号
void IIC_Start(void)
{
	SDA_OUT();     //sda线输出
	IIC_SDA = 1;	  	  
	IIC_SCL = 1;
	Delay_4us();
 	IIC_SDA = 0;//START:when CLK is high,DATA change form high to low 
	Delay_4us();
	
	IIC_SCL=0;//钳住I2C总线，准备发送或接收数据 
}	

//产生IIC起始信号
void IIC_ResStart(void)
{    
	IIC_SCL = 0;//时钟输出0 

    SDA_OUT();     //sda线输出
	Delay_2us();
    IIC_SDA = 1;
	
    IIC_SCL = 1;
    Delay_4us();
    IIC_SDA = 0;//START:when CLK is high,DATA change form high to low 
    Delay_4us();
	
	IIC_SCL=0;//钳住I2C总线，准备发送或接收数据 
}

//产生IIC停止信号
void IIC_Stop(void)
{	
    IIC_SCL = 0;   //IIC_SDAL;//STOP:when CLK is high DATA change form low to high
	SDA_OUT();  //sda线输出
	IIC_SDA = 0;
	Delay_4us();
	IIC_SCL = 1; 
	Delay_4us();
    IIC_SDA = 1;//发送I2C总线结束信号
    Delay_4us();	
}

//等待应答信号到来
//返回值：1，接收应答失败
//        0，接收应答成功
uint8_t IIC_Wait_Ack(void)
{
	uint8_t ucErrTime=0;
    volatile uint8_t i = 0;

	IIC_SCL = 0;
	i++;
    i++;
    i++;
	SDA_IN();      //SDA设置为输入 
	
	Delay_4us();	
	IIC_SCL = 1;
	Delay_4us();
	
	while(READ_SDA)
	{
		ucErrTime++;
		if(ucErrTime > 250)
		{
			IIC_Stop();
			return 1;
		}
	}
	IIC_SCL = 0;//时钟输出0
    Delay_2us();	
	return 0;  
} 

//产生ACK应答
void IIC_Ack(void)
{
	IIC_SCL = 0;
	Delay_4us();
	SDA_OUT();
	IIC_SDA = 0;
	Delay_4us();
	IIC_SCL = 1;
	Delay_4us();
	IIC_SCL = 0;
}

//不产生ACK应答		    
void IIC_NAck(void)
{
	IIC_SCL = 0;
	SDA_OUT();
	IIC_SDA = 1;
	Delay_4us();
	IIC_SCL = 1;
	Delay_4us();
	
	IIC_SCL = 0;
}

//IIC发送一个字节
//返回从机有无应答
//1，有应答
//0，无应答			  
void IIC_Write_Byte(uint8_t txd)
{                        
    uint8_t t; 
    volatile uint8_t i = 0;

    IIC_SCL = 0;//拉低时钟开始数据传输
	i++;
    i++;
    i++;
	SDA_OUT(); 	    
    
    for(t=0;t<8;t++)
    {              
        IIC_SCL = 0;	
		
		if((txd&0x80)>>7)
			IIC_SDA = 1;
		else
			IIC_SDA = 0;
		
		txd<<=1; 	  
		Delay_4us();
		IIC_SCL = 1;
		Delay_4us(); 
    }	
    IIC_SCL = 0;	
} 

//读1个字节，ack=1时，发送ACK，ack=0，发送nACK   
uint8_t IIC_Read_Byte(uint8_t ack)
{
	uint8_t i,receive = 0;
	volatile uint8_t k = 0;

	IIC_SCL = 0; 
    k++;
	k++;
	k++;
	SDA_IN();//SDA设置为输入
	
    for(i=0;i<8;i++ )
	{
        IIC_SCL = 0; 
        Delay_4us();
		IIC_SCL = 1;
        receive <<= 1;
        if(READ_SDA)
			receive++;   
		Delay_4us(); 
    }	
	
	//clk --> H
	
    if (!ack)
        IIC_NAck();//发送nACK
    else
        IIC_Ack(); //发送ACK   
    return receive;
}

//在AT24CXX指定地址读出一个数据
//ReadAddr:开始读数的地址  
//返回值  :读到的数据
uint8_t AT24CXX_ReadOneByte(uint16_t ReadAddr)
{	
    uint16_t temp;
    
    #if EEPROMSIZE
    IIC_Write_Byte(0XA0);	    //发送写命令
	IIC_Wait_Ack();
	IIC_Write_Byte(ReadAddr>>8);//发送高地址  
    IIC_Wait_Ack(); 
    #else
    IIC_Start();
	IIC_Write_Byte(0XA0 + ((ReadAddr>>8)<<1));   //发送器件地址0XA0,写数据 	 
	IIC_Wait_Ack();     
    #endif
    
    IIC_Write_Byte(ReadAddr%256);   //发送低地址
	IIC_Wait_Ack();	 
	
	IIC_ResStart();   	
	
	IIC_Write_Byte(0XA1);           //进入接收模式			   
	IIC_Wait_Ack();	
	
    temp = IIC_Read_Byte(0);	
	
    IIC_Stop();//产生一个停止条件	    
	return temp;
}

