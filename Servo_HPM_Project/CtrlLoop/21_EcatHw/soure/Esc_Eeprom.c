void AT24CXX_WriteOnePage(uint16_t WriteAddr,uint8_t *DataToWrite,uint8_t len)
{
	uint8_t i = 0;
	
    IIC_Start();  
        
    #if EEPROMSIZE
    IIC_Write_Byte(0XA0);	    //发送写命令
	IIC_Wait_Ack();
	IIC_Write_Byte(WriteAddr>>8);//发送高地址  
    IIC_Wait_Ack(); 
    #else
    IIC_Start();
	IIC_Write_Byte(0XA0 + ((WriteAddr>>8)<<1));   //发送器件地址0XA0,写数据 	 
	IIC_Wait_Ack();     
    #endif 
    
    IIC_Write_Byte(WriteAddr%256);   //发送低地址
    IIC_Wait_Ack(); 	

	Delay_4us();
	Delay_4us();
	for(i = 0;i<len; i++)
	{
        IIC_Write_Byte(*DataToWrite);     //发送字节							   
        IIC_Wait_Ack();  
		DataToWrite++;
		Delay_4us();
		Delay_4us();
	}

    IIC_Stop();//产生一个停止条件		
}

void ESC_Write_EEPROM(void)
{
	uint16_t i = 0,j = 0; 
    
    R_MPC_WriteEnable();
	MPC.PC4PFS.BYTE = 0x00;	  // PC4 : CATI2CCLK
	MPC.PC5PFS.BYTE = 0x00;	  // PC5 : CATI2CDATA
    R_MPC_WriteDisable();

    PORTC.PDR.BIT.B4 = 0;     // Initialize port settings
    PORTC.PMR.BIT.B4 = 0;
  
    PORTC.PODR.BIT.B4 = 1;    // Set output level to High
    PORTC.PDR.BIT.B4 = 3;     // Set port direction to output 
    
    PORTC.PDR.BIT.B5 = 0;     // Initialize port settings
    PORTC.PMR.BIT.B5 = 0;
  
    PORTC.PODR.BIT.B5 = 1;    // Set output level to High
    PORTC.PDR.BIT.B5 = 3;     // Set port direction to output 

    for(i=0; i<64; i++)
    {
        AT24CXX_WriteOnePage(j,(uint8_t*)&EEPROM_XML[j],32);
        j=j+32;
        Delay(2000);
    }
    
    Delay(2000);
    
    R_MPC_WriteEnable();
	MPC.PC4PFS.BYTE = 0x16;						// PC4 : CATI2CCLK
	MPC.PC5PFS.BYTE = 0x16;						// PC5 : CATI2CDATA
    R_MPC_WriteDisable();
    
    PORTC.PMR.BIT.B4 = 1;						// PC0-PC5 :
    PORTC.PMR.BIT.B5 = 1;						// PC0-PC5 :
}

